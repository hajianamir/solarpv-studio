CREATE TABLE IF NOT EXISTS projects (
    id UUID PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS pv_modules (
    id UUID PRIMARY KEY,
    manufacturer VARCHAR(150) NOT NULL,
    model_name VARCHAR(150) NOT NULL,
    p_mp_w DOUBLE PRECISION NOT NULL,
    v_mp_v DOUBLE PRECISION NOT NULL,
    v_oc_v DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS inverters (
    id UUID PRIMARY KEY,
    manufacturer VARCHAR(150) NOT NULL,
    model_name VARCHAR(150) NOT NULL,
    p_nom_ac_kw DOUBLE PRECISION NOT NULL,
    v_vdc_max_v DOUBLE PRECISION NOT NULL,
    v_mppt_min_v DOUBLE PRECISION NOT NULL,
    v_mppt_max_v DOUBLE PRECISION NOT NULL
);
