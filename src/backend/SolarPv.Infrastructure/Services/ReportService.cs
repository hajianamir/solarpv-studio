namespace SolarPv.Infrastructure.Services;

using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using SolarPv.Application.Services;

public class ReportService : IReportService
{
    public ReportService()
    {
        QuestPDF.Settings.License = LicenseType.Community;
    }

    public byte[] GeneratePdfReport(GenerateReportRequest request)
    {
        var document = Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Size(PageSizes.A4);
                page.Margin(2, Unit.Centimetre);
                page.PageColor(Colors.White);
                page.DefaultTextStyle(x => x.FontSize(11).FontColor(Colors.Grey.Darken3));

                page.Header()
                    .Text("SolarPV Studio — Official EPC Design Proposal")
                    .SemiBold().FontSize(18).FontColor(Colors.Blue.Darken2);

                page.Content()
                    .PaddingVertical(1, Unit.Centimetre)
                    .Column(x =>
                    {
                        x.Spacing(12);

                        x.Item().Text($"Project Name: {request.ProjectName}").Bold().FontSize(14);
                        x.Item().Text($"Project ID: {request.ProjectId}");

                        x.Item().Table(table =>
                        {
                            table.ColumnsDefinition(columns =>
                            {
                                columns.ConstantColumn(200);
                                columns.RelativeColumn();
                            });

                            table.Header(header =>
                            {
                                header.Cell().Element(CellStyleHeader).Text("Component / Metric").Bold();
                                header.Cell().Element(CellStyleHeader).Text("Specification / Value").Bold();

                                static IContainer CellStyleHeader(IContainer container)
                                {
                                    return container.DefaultTextStyle(x => x.Bold())
                                                    .PaddingVertical(5)
                                                    .BorderBottom(1)
                                                    .BorderColor(Colors.Grey.Lighten2);
                                }
                            });

                            table.Cell().Element(CellStyleBody).Text("System Capacity");
                            table.Cell().Element(CellStyleBody).Text($"{request.SystemCapacityKwp:F2} kWp");

                            table.Cell().Element(CellStyleBody).Text("PV Solar Panels");
                            table.Cell().Element(CellStyleBody).Text($"{request.PanelCount} x 575W N-Type Panels");

                            table.Cell().Element(CellStyleBody).Text("String Inverters");
                            table.Cell().Element(CellStyleBody).Text($"{request.InverterCount} x 10kW String Inverters");

                            table.Cell().Element(CellStyleBody).Text("Battery Energy Storage");
                            table.Cell().Element(CellStyleBody).Text($"{request.BatteryCount} x 10.2kWh LiFePO4 Units");

                            table.Cell().Element(CellStyleBody).Text("Annual Energy Yield");
                            table.Cell().Element(CellStyleBody).Text($"{request.AnnualYieldKwh:N0} kWh/year");

                            table.Cell().Element(CellStyleBody).Text("Levelized Cost of Energy (LCOE)");
                            table.Cell().Element(CellStyleBody).Text($"${request.LcoeUsdPerKwh:F4} / kWh");

                            static IContainer CellStyleBody(IContainer container)
                            {
                                return container.PaddingVertical(5)
                                                .BorderBottom(1)
                                                .BorderColor(Colors.Grey.Lighten3);
                            }
                        });
                    });

                page.Footer()
                    .AlignCenter()
                    .Text(x =>
                    {
                        x.Span("Generated by SolarPV Studio Core Simulation Engine | Page ");
                        x.CurrentPageNumber();
                    });
            });
        });

        return document.GeneratePdf();
    }
}
